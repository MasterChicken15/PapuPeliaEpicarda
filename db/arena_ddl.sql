CREATE TABLE tipos_clase (
    tipo_clase  VARCHAR2(30 CHAR)  NOT NULL,
    descripcion VARCHAR2(120 CHAR),
    CONSTRAINT pk_tipos_clase PRIMARY KEY (tipo_clase)
);



CREATE TABLE personajes (
    id             VARCHAR2(36 CHAR)  NOT NULL,          
    tipo_clase     VARCHAR2(30 CHAR)  NOT NULL,
    nombre         VARCHAR2(60 CHAR)  NOT NULL,
    vida           NUMBER(6)          NOT NULL,
    vida_maxima    NUMBER(6)          NOT NULL,
    fuerza         NUMBER(6)          NOT NULL,
    poder          NUMBER(6)          NOT NULL,
    defensa        NUMBER(6)          NOT NULL,
    arma           VARCHAR2(60 CHAR),
    ruta_imagen    VARCHAR2(255 CHAR),                   
    activo         NUMBER(1)          DEFAULT 1 NOT NULL,  
    creado_en      TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
    actualizado_en TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_personajes        PRIMARY KEY (id),
    CONSTRAINT uq_personajes_nombre UNIQUE (nombre),
    CONSTRAINT fk_personajes_clase  FOREIGN KEY (tipo_clase)
        REFERENCES tipos_clase (tipo_clase),
    CONSTRAINT ck_personajes_vida   CHECK (vida >= 0 AND vida <= vida_maxima),
    CONSTRAINT ck_personajes_activo CHECK (activo IN (0, 1))
);

CREATE OR REPLACE TRIGGER trg_personajes_upd
BEFORE UPDATE ON personajes
FOR EACH ROW
BEGIN
    :NEW.actualizado_en := SYSTIMESTAMP;
END;
/



CREATE TABLE personaje_atributo (
    personaje_id VARCHAR2(36 CHAR)  NOT NULL,
    clave        VARCHAR2(40 CHAR)  NOT NULL,
    valor        VARCHAR2(255 CHAR),
    tipo_dato    VARCHAR2(10)       DEFAULT 'STRING' NOT NULL,
    CONSTRAINT pk_personaje_atributo PRIMARY KEY (personaje_id, clave),
    CONSTRAINT fk_atributo_personaje FOREIGN KEY (personaje_id)
        REFERENCES personajes (id) ON DELETE CASCADE,
    CONSTRAINT ck_atributo_tipo CHECK (tipo_dato IN ('INT', 'STRING', 'BOOL'))
);



CREATE TABLE combates (
    id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    modo          VARCHAR2(20)       DEFAULT '1V1' NOT NULL,
    estado        VARCHAR2(12)       DEFAULT 'EN_CURSO' NOT NULL,
    iniciado_en   TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
    finalizado_en TIMESTAMP,
    ganador_id    VARCHAR2(36 CHAR),
    total_turnos  NUMBER(6)          DEFAULT 0 NOT NULL,
    notas         VARCHAR2(255 CHAR),
    CONSTRAINT pk_combates PRIMARY KEY (id),
    CONSTRAINT fk_combate_ganador FOREIGN KEY (ganador_id)
        REFERENCES personajes (id) ON DELETE SET NULL,
    CONSTRAINT ck_combate_modo   CHECK (modo IN ('1V1', 'EQUIPOS', 'TODOS_CONTRA_TODOS')),
    CONSTRAINT ck_combate_estado CHECK (estado IN ('EN_CURSO', 'FINALIZADO', 'ABANDONADO'))
);



CREATE TABLE combate_participante (
    combate_id      NUMBER            NOT NULL,
    personaje_id    VARCHAR2(36 CHAR) NOT NULL,
    equipo          NUMBER(3)         DEFAULT 0 NOT NULL,   -- 0 = individual
    vida_inicial    NUMBER(6)         NOT NULL,
    fuerza_inicial  NUMBER(6)         NOT NULL,
    poder_inicial   NUMBER(6)         NOT NULL,
    defensa_inicial NUMBER(6)         NOT NULL,
    vida_final      NUMBER(6),
    fuerza_final    NUMBER(6),
    poder_final     NUMBER(6),
    sobrevivio      NUMBER(1),
    CONSTRAINT pk_combate_participante PRIMARY KEY (combate_id, personaje_id),
    CONSTRAINT fk_part_combate FOREIGN KEY (combate_id)
        REFERENCES combates (id) ON DELETE CASCADE,
    CONSTRAINT fk_part_personaje FOREIGN KEY (personaje_id)
        REFERENCES personajes (id),
    CONSTRAINT ck_part_sobrevivio CHECK (sobrevivio IN (0, 1))
);



CREATE TABLE combate_turno (
    id                    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    combate_id            NUMBER            NOT NULL,
    numero_turno          NUMBER(6)         NOT NULL,
    atacante_id           VARCHAR2(36 CHAR) NOT NULL,
    objetivo_id           VARCHAR2(36 CHAR),            -- NULL si la accion no tiene objetivo
    accion                VARCHAR2(20)      DEFAULT 'ATAQUE_BASICO' NOT NULL,
    dano_bruto            NUMBER(6)         DEFAULT 0 NOT NULL,
    dano_neto             NUMBER(6)         DEFAULT 0 NOT NULL,
    vida_objetivo_despues NUMBER(6),
    descripcion           VARCHAR2(500 CHAR),
    ocurrido_en           TIMESTAMP         DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_combate_turno PRIMARY KEY (id),
    CONSTRAINT uq_turno UNIQUE (combate_id, numero_turno, atacante_id),
    CONSTRAINT fk_turno_combate FOREIGN KEY (combate_id)
        REFERENCES combates (id) ON DELETE CASCADE,
    CONSTRAINT fk_turno_atacante FOREIGN KEY (atacante_id)
        REFERENCES personajes (id),
    CONSTRAINT fk_turno_objetivo FOREIGN KEY (objetivo_id)
        REFERENCES personajes (id),
    CONSTRAINT ck_turno_accion CHECK
        (accion IN ('ATAQUE_BASICO', 'HABILIDAD_ESPECIAL', 'DEFENSA', 'OTRA'))
);



CREATE INDEX idx_part_personaje   ON combate_participante (personaje_id);
CREATE INDEX idx_turno_atacante   ON combate_turno (atacante_id);
CREATE INDEX idx_turno_objetivo   ON combate_turno (objetivo_id);
CREATE INDEX idx_combate_ganador  ON combates (ganador_id);
CREATE INDEX idx_personajes_clase ON personajes (tipo_clase);



CREATE OR REPLACE VIEW v_ranking AS
SELECT p.id,
       p.nombre,
       p.tipo_clase,
       COUNT(DISTINCT cp.combate_id)                                   AS combates,
       COUNT(DISTINCT CASE WHEN c.ganador_id = p.id THEN c.id END)     AS victorias,
       COUNT(DISTINCT cp.combate_id)
         - COUNT(DISTINCT CASE WHEN c.ganador_id = p.id THEN c.id END) AS no_victorias,
       NVL((SELECT SUM(t.dano_neto) FROM combate_turno t
            WHERE t.atacante_id = p.id), 0)                            AS dano_total_causado
FROM personajes p
LEFT JOIN combate_participante cp ON cp.personaje_id = p.id
LEFT JOIN combates c ON c.id = cp.combate_id AND c.estado = 'FINALIZADO'
GROUP BY p.id, p.nombre, p.tipo_clase;

CREATE OR REPLACE VIEW v_historial_combates AS
SELECT c.id AS combate_id, c.modo, c.estado, c.iniciado_en, c.finalizado_en,
       c.total_turnos, g.nombre AS ganador
FROM combates c
LEFT JOIN personajes g ON g.id = c.ganador_id;
